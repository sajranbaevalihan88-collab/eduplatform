SENT_SPLIT = re.compile(r'(?<=[.!?…])\s+')
WORD = re.compile(r'[A-Za-zА-Яа-яЁёҮүӨөҢң]{4,}')


def extract_requested_count(prompt: str, fallback: int = 5, min_val: int = 1, max_val: int = 40) -> int:
    """Извлекает количество вопросов/слов из промпта учителя.
    Примеры:
      'сделай мне вопросы по пайтону 14 вопросов' -> 14
      'сгенерируй 12 тестовых заданий для 8 класса' -> 12
      '20 questions about python' -> 20
      'кыргыз тили боюнча 15 суроо' -> 15
    """
    s = str(prompt or '').strip().lower()
    if not s:
        return max(min_val, min(max_val, int(fallback or 5)))

    # 1. Явное указание: ЧИСЛО + (вопросов/суроо/questions/заданий/штук/слов/сөз)
    m = re.search(
        r'\b(\d{1,2})\s*(?:вопрос\w*|вопр\.?|суроо\w*|question\w*|q\b|задани\w*|тест\w*|шт\.?|штук\w*|пример\w*|слов\w*|сөз\w*|word\w*)',
        s
    )
    if m:
        val = int(m.group(1))
        if min_val <= val <= max_val:
            return val

    # 2. Обратный порядок: 'вопросов: 14' / 'количество 14' / 'штук 14'
    m2 = re.search(
        r'(?:вопрос\w*|суроо\w*|question\w*|количеств\w*|кол-во|штук|слов\w*|сөз\w*)\s*[:=\-]?\s*(\d{1,2})\b',
        s
    )
    if m2:
        val = int(m2.group(1))
        if min_val <= val <= max_val:
            return val

    # Если число не сопровождается словом «вопросов/суроо/questions», используем значение из поля количества (fallback),
    # чтобы числа из названия темы («Word 2016», «1) Создание 2) Форматирование», «Тема 1») не сбивали выбранное количество.
    return max(min_val, min(max_val, int(fallback or 5)))


def clean_topic_title(prompt: str) -> str:
    """Очищает тему от служебных слов вроде 'сделай мне вопросы по ... 14 вопросов'."""
    s = str(prompt or '').strip()
    s = re.sub(r'(?i)\b(?:сделай|создай|составь|сгенерируй|придумай|дай|напиши|мне|нам|пожалуйста|плиз|нужно|надо)\b', ' ', s)
    s = re.sub(r'(?i)\b\d{1,2}\s*(?:вопрос\w*|вопр\.?|суроо\w*|question\w*|задани\w*|шт\.?|штук\w*|слов\w*)\b', ' ', s)
    s = re.sub(r'(?i)\b(?:вопрос\w*|тест\w*|игр\w*|викторин\w*|кахут|kahoot)\s*(?:по\s+теме|по|на\s+тему|про|о|об|боюнча)?\b', ' ', s)
    s = re.sub(r'(?i)^\s*(?:по\s+теме|по|на\s+тему|про|о|об|для)\s+', '', s)
    s = re.sub(r'\s+', ' ', s).strip(' ,.:;-!?«»"\'')
    return s or 'Общая эрудиция'


def _sentences(text):
    parts = [s.strip() for s in SENT_SPLIT.split(text or '') if s.strip()]
    return [s for s in parts if len(s) >= 25]


def _definitions(sentences):
    out = []
    pat = re.compile(r'^([A-ZА-ЯЁҮӨҢ][\w\s\-]{2,40}?)\s*[—:\-–]\s*(.{15,200})$')
    pat2 = re.compile(r'^([A-ZА-ЯЁҮӨҢ][\w\s\-]{2,40}?)\s+это\s+(.{15,200})$')
    for s in sentences:
        s1 = s.rstrip('.!?…')
        m = pat.match(s1) or pat2.match(s1)
        if m:
            term, defi = m.group(1).strip(), m.group(2).strip()
            if len(term.split()) <= 4:
                out.append((term, defi))
    return out


def _make_q(text: str, correct: str, wrongs: list, explanation: str = '', qtype: str = 'single') -> dict:
    if qtype == 'true_false':
        is_true = str(correct).lower() in ('верно', 'правда', 'true', 'да', '1')
        return {
            'text': text,
            'type': 'true_false',
            'points': 1,
            'explanation': explanation,
            'options': [
                {'text': 'Верно', 'is_correct': is_true},
                {'text': 'Неверно', 'is_correct': not is_true},
            ],
        }
    opts = [{'text': str(correct), 'is_correct': True}]
    for w in wrongs[:3]:
        opts.append({'text': str(w), 'is_correct': False})
    while len(opts) < 4:
        opts.append({'text': f'Вариант {len(opts) + 1}', 'is_correct': False})
    random.shuffle(opts)
    return {
        'text': text,
        'type': 'single',
        'points': 1,
        'explanation': explanation,
        'options': opts,
    }


