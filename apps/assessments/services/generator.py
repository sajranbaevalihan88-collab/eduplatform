def generate_questions(text, count=5):
    """Извлекает вопросы из текста урока (определения + факты)."""
    sentences = _sentences(text)
    if len(sentences) < 2:
        return []
    defs = _definitions(sentences)
    questions = []
    for i, (term, defi) in enumerate(defs):
        if len(questions) >= count:
            break
        others = [d for j, (t2, d) in enumerate(defs) if j != i][:3]
        while len(others) < 3:
            others.append('Ничего из перечисленного')
        options = [{'text': defi[:200], 'is_correct': True}]
        options += [{'text': o[:200], 'is_correct': False} for o in others[:3]]
        random.shuffle(options)
        questions.append({
            'text': f'Что такое «{term}»?',
            'type': 'single', 'points': 1, 'options': options,
            'explanation': f'Ответ — из текста урока: {defi[:150]}',
        })
    facts = [s for s in sentences if len(s) > 40 and not any(t in s for t, _ in defs)]
    for i, s in enumerate(facts):
        if len(questions) >= count:
            break
        is_true = (i % 2 == 0)
        if is_true:
            questions.append({
                'text': f'Верно ли: {s[:220]}',
                'type': 'true_false', 'points': 1,
                'options': [{'text': 'Верно', 'is_correct': True}, {'text': 'Неверно', 'is_correct': False}],
                'explanation': 'Утверждение из текста урока.',
            })
        else:
            neg = re.sub(r'\s(есть|был|была|были|будет|может|должен)\b', r' не \1', s[:220], count=1)
            if neg == s[:220]:
                neg = 'Неверно, что: ' + s[:200]
            questions.append({
                'text': f'Верно ли: {neg}',
                'type': 'true_false', 'points': 1,
                'options': [{'text': 'Верно', 'is_correct': False}, {'text': 'Неверно', 'is_correct': True}],
                'explanation': 'Проверь текст урока — здесь подвох.',
            })
    return questions[:count]


def generate_smart_topic_questions(prompt: str = '', text: str = '', count: int = 5) -> list:
    """Умный генератор вопросов по промпту учителя и/или тексту урока.
    Всегда возвращает РОВНО `count` вопросов по запрошенной теме!"""
    count = max(1, min(40, int(count or 5)))
    questions = []
    seen_texts = set()

    def _add(q_obj):
        t = (q_obj.get('text') or '').strip()
        if t and t not in seen_texts and len(questions) < count:
            seen_texts.add(t)
            questions.append(q_obj)

    # 1. Если передан содержательный текст урока — сначала извлекаем из него
    if isinstance(text, str) and len(text.strip()) >= 120:
        for q in generate_questions(text, count):
            _add(q)

    # 2. Определяем тематику по промпту и тексту
    combined = f'{prompt or ""} {(text or "")[:600]}'.lower()

    is_word_docs = bool(re.search(r'(\bword\b|ворд|google\s*док|google\s*doc|текстов\w*\s+редактор|текстов\w*\s+процессор|оформлени\w*\s+документ|редактирован\w*\s+документ|создани\w*\s+документ|колонтитул|абзац|шрифт|docx)', combined))
    is_excel = bool(re.search(r'(\bexcel\b|эксел|электронн\w*\s+таблиц|google\s*таблиц|google\s*sheet|ячейк|формул\w*\s+в|диапазон|сумм\b|впр\b|xlsx)', combined))
    is_atoms_chem = bool(re.search(r'(\bатом\w*|молекул\w*|протон|нейтрон|электрон|менделеев|хими\w*|элемент\w*|валентност|изотоп|ядр\w*\s+атом|веществ)', combined))
    is_python = bool(re.search(r'(python|пайтон|питон|def\b|print|список|цикл|программир|код)', combined))
    is_cs = bool(re.search(r'(информатик|информаци|компьютер|алгоритм|html|css|sql|баз\w*\s+данных|байт|бит|сеть|ии|ai\b|презентац|powerpoint|pptx|файл\w*|папк\w*)', combined))
    is_math = bool(re.search(r'(математ|алгебр|геометр|уравнен|дроб|треугольник|площад|корень|степен|числ|функци|тетраэдр|многогранник)', combined))
    is_kg_hist = bool(re.search(r'(кыргызстан|истори|манас|бишкек|иссык|айматов|айтматов|родин|мекен|тарых|каганат)', combined))
    is_kg_lang = bool(re.search(r'(кыргыз\s+тил|кыргызча|жөндөмө|зат\s+атооч|этиш|макал|тамга)', combined))
    is_rus_lang = bool(re.search(r'(русск\w*\s+язык|грамматик|орфограф|пунктуац|существительн|глагол|прилагательн|подлежащ|сказуем|приставк|суффикс|синоним|антоним)', combined))
    is_eng = bool(re.search(r'(англ|english|grammar|present|past|verb|vocabulary|debate)', combined))
    is_sci = bool(re.search(r'(физик|биолог|географ|космос|планет|клетк|энерги|природ|естествозн|закон\w*\s+ньютон|ом\b)', combined))

    pool = []
    if is_word_docs:
        pool.extend(WORD_DOCS_BANK)
    if is_excel:
        pool.extend(EXCEL_BANK)
    if is_atoms_chem:
        pool.extend(ATOMS_CHEMISTRY_BANK)
    if is_python:
        pool.extend(PYTHON_BANK)
    if is_cs:
        pool.extend(CS_BANK)
    if is_math:
        pool.extend(MATH_BANK)
    if is_kg_hist:
        pool.extend(KG_HISTORY_BANK)
    if is_kg_lang:
        pool.extend(KYRGYZ_LANG_BANK)
    if is_rus_lang:
        pool.extend(RUSSIAN_LANG_BANK)
    if is_eng:
        pool.extend(ENGLISH_BANK)
    if is_sci:
        pool.extend(SCIENCE_BANK)

    # Сначала берём профильные вопросы из совпавших банков
    for item in pool:
        if len(questions) >= count:
            break
        _add(_make_q(item[0], item[1], item[2], item[3]))

    if len(questions) < count:
        rem = count - len(questions)
        if is_python:
            for q in _procedural_python_questions(rem + 5):
                _add(q)
        elif is_math:
            for q in _procedural_math_questions(rem + 5):
                _add(q)
        elif is_word_docs or is_excel or is_cs:
            # Добираем смежными вопросами по ИКТ и офисным пакетам (без повторов!)
            for extra_bank in (CS_BANK, WORD_DOCS_BANK, EXCEL_BANK, PYTHON_BANK):
                for item in extra_bank:
                    if len(questions) >= count:
                        break
                    _add(_make_q(item[0], item[1], item[2], item[3]))
        elif is_atoms_chem or is_sci:
            for extra_bank in (ATOMS_CHEMISTRY_BANK, SCIENCE_BANK):
                for item in extra_bank:
                    if len(questions) >= count:
                        break
                    _add(_make_q(item[0], item[1], item[2], item[3]))

    # Если промпт на произвольную тему или всё ещё нужно добрать до count
    if len(questions) < count and (prompt or '').strip():
        rem = count - len(questions)
        for q in _procedural_topic_questions(prompt, rem, start_idx=len(questions) + 1):
            _add(q)

    # Финальная страховка из всех предметных банков (чтобы 30–40 вопросов всегда были 100% уникальными)
    if len(questions) < count:
        for bank in (CS_BANK, WORD_DOCS_BANK, EXCEL_BANK, ATOMS_CHEMISTRY_BANK, SCIENCE_BANK, MATH_BANK, PYTHON_BANK, KG_HISTORY_BANK, RUSSIAN_LANG_BANK):
            for item in bank:
                if len(questions) >= count:
                    break
                _add(_make_q(item[0], item[1], item[2], item[3]))

    return questions[:count]


