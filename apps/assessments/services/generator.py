def generate_smart_topic_words(prompt: str = '', count: int = 10) -> list:
    """Подбирает ровно `count` слов по теме (для Виселицы и Найди слово)."""
    count = max(3, min(20, extract_requested_count(prompt, fallback=count, min_val=3, max_val=20)))
    s = (prompt or '').lower()
    pool = []
    if re.search(r'(python|пайтон|питон|код|программир|ит\b|it\b|информатик)', s):
        pool.extend(TOPIC_WORDS_BANK['python'])
    if re.search(r'(математ|алгебр|геометр|числ|уравнен)', s):
        pool.extend(TOPIC_WORDS_BANK['math'])
    if re.search(r'(кыргызстан|манас|бишкек|истори|родин|тарых)', s):
        pool.extend(TOPIC_WORDS_BANK['kg'])
    if re.search(r'(физик|хими|биолог|космос|наук|природ)', s):
        pool.extend(TOPIC_WORDS_BANK['science'])
    if re.search(r'(english|англ|[a-z]{4,})', s) and not re.search(r'(python|пайтон)', s):
        pool.extend(TOPIC_WORDS_BANK['english'])
    if re.search(r'(кыргыз\s+тил|кыргызча|[үөң])', s):
        pool.extend(TOPIC_WORDS_BANK['kyrgyz_lang'])

    if not pool:
        for k in ('python', 'kg', 'science', 'math'):
            pool.extend(TOPIC_WORDS_BANK[k])

    seen = set()
    out = []
    for w in pool:
        if w not in seen and 3 <= len(w) <= 12:
            seen.add(w)
            out.append(w)
        if len(out) >= count:
            break
    return out[:count]
