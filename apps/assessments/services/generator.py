def _procedural_python_questions(needed: int) -> list:
    """Генерирует уникальные задачи по Python с вычислением кода, чтобы хватило на любое число вопросов (14, 25, 40)."""
    out = []
    patterns = [
        lambda idx: (
            f'Что выведет код на Python: print({idx + 2} * 3 + {idx % 5 + 1})?',
            str((idx + 2) * 3 + (idx % 5 + 1)),
            [str(((idx + 2) + (idx % 5 + 1)) * 3), str((idx + 2) * 4), 'Ошибка SyntaxError'],
            f'Сначала умножение: {idx + 2} * 3 = {(idx + 2) * 3}, затем прибавляем {idx % 5 + 1}.'
        ),
        lambda idx: (
            f'Чему равен результат среза строки s = "БИШКЕК": s[0:{(idx % 4) + 2}]?',
            'БИШКЕК'[0:(idx % 4) + 2],
            ['БИШКЕК'[1:(idx % 4) + 3], 'БИШКЕК', 'К'],
            f'Срез s[0:{(idx % 4) + 2}] берёт первые {(idx % 4) + 2} символа строки.'
        ),
        lambda idx: (
            f'Что выведет Python-код: a = [{idx + 1}, {idx + 3}, {idx + 5}, {idx + 7}]; print(a[{idx % 4}])?',
            str([idx + 1, idx + 3, idx + 5, idx + 7][idx % 4]),
            [str([idx + 1, idx + 3, idx + 5, idx + 7][(idx + 1) % 4]), str(idx % 4), 'IndexError'],
            f'Индексация списков в Python начинается с 0, поэтому элемент с индексом {idx % 4} равен {[idx + 1, idx + 3, idx + 5, idx + 7][idx % 4]}.'
        ),
        lambda idx: (
            f'Сколько раз выполнится тело цикла: for i in range({idx + 3}): print(i)?',
            f'{idx + 3} раза' if (idx + 3) in (2, 3, 4) else f'{idx + 3} раз',
            [f'{idx + 2} раз', f'{idx + 4} раз', 'Бесконечно'],
            f'range({idx + 3}) генерирует числа от 0 до {idx + 2} включительно — ровно {idx + 3} итераций.'
        ),
        lambda idx: (
            f'Чему равно выражение bool({idx + 1} > {idx}) and bool({idx + 2} == {idx + 2}) в Python?',
            'True',
            ['False', 'None', '10'],
            'Оба сравнения истинны, поэтому оператор and возвращает True.'
        ),
    ]
    for i in range(needed):
        fn = patterns[i % len(patterns)]
        q_text, corr, wr, exp = fn(i + 1)
        out.append(_make_q(q_text, corr, wr, exp))
    return out


