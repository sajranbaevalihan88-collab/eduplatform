def _find_line(output, code):
    """Номер строки ошибки из traceback (File ... line N) или 'строка X'."""
    m = re.search(r'File "?",? line (\d+)|line (\d+)', output)
    if m:
        return int(m.group(1) or m.group(2))
    m = re.search(r'строка (\d+)', output)
    if m:
        return int(m.group(1))
    return None


def explain(code, language, output):
    """Возвращает dict {title, what, fix, line} или None если шаблонов нет."""
    language = (language or '').lower().strip()
    patterns = PY_PATTERNS if language == 'python' else JS_PATTERNS if language == 'javascript' else None
    if patterns is None:
        return None
    text = output or ''
    for pattern, title, what, fix in patterns:
        m = re.search(pattern, text)
        if m:
            groups = [g for g in m.groups() if g]
            fmt = lambda s: s.format(*groups) if groups else s
            try:
                t, w, f = fmt(title), fmt(what), fmt(fix)
            except Exception:
                t, w, f = title, what, fix
            return {'title': t, 'what': w, 'fix': f, 'line': _find_line(text, code)}
    return None
