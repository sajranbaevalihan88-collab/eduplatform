// Prefix/suffix symbols preserved automatically around dictionary lookup
const EDGE_RE = /^([\s🛡🛡️✨⚡🔥🔒🌐📡👁️👁💬🗳️🩺🎩🕶️🏘️⭐📓📌🎯🏆🥇🤖🔄💥❤️⏱⚙️✏️📷➕+\-←→↑↓↗‹›•·✓✕×⚠⚠️🚫🗑️📅⏰📚📝💡👏🎉👋🤝☀️🌙🔊🔇⬜⬛🟦🟨🔴🟡🧱🧑‍🌾⚔️⌨️🐒🎨🔎🎵🤼🕵️🧰🏔️💰Ω]+)?([\s\S]*?)([\s←→↑↓↗‹›…!?*✓✕]+)?$/u

const HAS_CYRILLIC = /[А-Яа-яЁё]/
const HAS_KYRGYZ_ONLY = /[өүңӨҮҢ]/

function translateCore(raw: string, lang: 'en' | 'kg'): string | null {
  const norm = raw.replace(/\s+/g, ' ').trim()
  if (!norm || !HAS_CYRILLIC.test(norm) || HAS_KYRGYZ_ONLY.test(norm)) return null

  const idx = lang === 'en' ? 0 : 1

  // 1. Direct exact hit
  if (DICT[norm]) return DICT[norm][idx]

  // 2. Strip leading/trailing emojis/arrows/punctuation and look up core
  const m = norm.match(EDGE_RE)
  if (m) {
    const pre = m[1] || ''
    const core = (m[2] || '').trim()
    const suf = m[3] || ''
    if (core && DICT[core]) {
      return `${pre}${DICT[core][idx]}${suf}`
    }
    // Check with trailing colon or punctuation attached
    if (core && suf && DICT[core + suf.trim()]) {
      return `${pre}${DICT[core + suf.trim()][idx]}`
    }
    // Check regex patterns on core
    for (const rule of PATTERNS) {
      const pm = core.match(rule.re)
      if (pm) {
        const out = lang === 'en' ? rule.en(...pm) : rule.kg(...pm)
        return `${pre}${out}${suf}`
      }
    }
  }

  // 3. Check regex patterns on full normalized string
  for (const rule of PATTERNS) {
    const pm = norm.match(rule.re)
    if (pm) {
      return lang === 'en' ? rule.en(...pm) : rule.kg(...pm)
    }
  }

  return null
}

function translateString(original: string, lang: 'en' | 'kg'): string {
  if (!original || !HAS_CYRILLIC.test(original) || HAS_KYRGYZ_ONLY.test(original)) return original
  const leadWs = original.match(/^\s*/)?.[0] || ''
  const trailWs = original.match(/\s*$/)?.[0] || ''
  const direct = translateCore(original, lang)
  if (direct !== null) return `${leadWs}${direct}${trailWs}`

  // Composite phrases separated by " • " or " · "
  const trimmed = original.trim()
  if (trimmed.includes(' • ') || trimmed.includes(' · ')) {
    const sep = trimmed.includes(' • ') ? ' • ' : ' · '
    const parts = trimmed.split(sep)
    let changed = false
    const mapped = parts.map(p => {
      const tr = translateCore(p, lang)
      if (tr !== null) { changed = true; return tr }
      return p
    })
    if (changed) return `${leadWs}${mapped.join(sep)}${trailWs}`
  }

  return original
}

const SKIP_TEXT_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE', 'KBD', 'TEXTAREA', 'SVG'])
const SKIP_ATTR_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE', 'KBD', 'SVG'])
const SKIP_SELECTOR = '.monaco-editor, .word-page, .cm-editor, .tl-text-shape, [contenteditable="true"], [data-no-translate]'
const ATTRS = ['placeholder', 'title', 'aria-label'] as const

const origText = new WeakMap<Text, string>()
const writtenText = new WeakMap<Text, string>()
const origAttr = new WeakMap<Element, Partial<Record<typeof ATTRS[number], string>>>()
const writtenAttr = new WeakMap<Element, Partial<Record<typeof ATTRS[number], string>>>()

let currentLang: Lang = 'ru'
let observer: MutationObserver | null = null
let rafId = 0
let dirtyRoots = new Set<Node>()

function isSkippedElement(el: Element | null, forAttr = false): boolean {
  if (!el) return true
  if (forAttr ? SKIP_ATTR_TAGS.has(el.tagName) : SKIP_TEXT_TAGS.has(el.tagName)) return true
  try {
    if (el.closest(SKIP_SELECTOR)) return true
  } catch { /* ignore */ }
  return false
}

function processTextNode(node: Text, lang: Lang) {
  const parent = node.parentElement
  if (!parent || isSkippedElement(parent)) return
  const cur = node.nodeValue || ''

  if (lang === 'ru') {
    const lastW = writtenText.get(node)
    if (lastW !== undefined && cur === lastW) {
      const orig = origText.get(node)
      if (orig !== undefined) node.nodeValue = orig
    }
    writtenText.delete(node)
    return
  }

  // If React updated the node text to something new (not our last written string), refresh original source
  const lastW = writtenText.get(node)
  let src: string
  if (lastW !== undefined && cur === lastW && origText.has(node)) {
    src = origText.get(node)!
  } else {
    src = cur
    origText.set(node, src)
  }

  const next = translateString(src, lang)
  if (next !== cur) {
    writtenText.set(node, next)
    node.nodeValue = next
  } else if (next === src) {
    writtenText.delete(node)
  }
}

function processElementAttrs(el: Element, lang: Lang) {
  if (isSkippedElement(el, true)) return
  for (const attr of ATTRS) {
    if (!el.hasAttribute(attr)) continue
    const cur = el.getAttribute(attr) || ''
    let oMap = origAttr.get(el)
    let wMap = writtenAttr.get(el)

    if (lang === 'ru') {
      if (wMap && wMap[attr] !== undefined && cur === wMap[attr]) {
        const orig = oMap?.[attr]
        if (orig !== undefined) el.setAttribute(attr, orig)
      }
      if (wMap) delete wMap[attr]
      continue
    }

    let src: string
    if (wMap && wMap[attr] !== undefined && cur === wMap[attr] && oMap && oMap[attr] !== undefined) {
      src = oMap[attr]!
    } else {
      src = cur
      if (!oMap) { oMap = {}; origAttr.set(el, oMap) }
      oMap[attr] = src
    }

    const next = translateString(src, lang)
    if (next !== cur) {
      if (!wMap) { wMap = {}; writtenAttr.set(el, wMap) }
      wMap[attr] = next
      el.setAttribute(attr, next)
    } else if (next === src && wMap) {
      delete wMap[attr]
    }
  }
}

function walkAndTranslate(root: Node, lang: Lang) {
  if (root.nodeType === Node.TEXT_NODE) {
    processTextNode(root as Text, lang)
    return
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return
  if (root.nodeType === Node.ELEMENT_NODE) {
    const el = root as Element
    if (isSkippedElement(el, true)) return
    processElementAttrs(el, lang)
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
  let n: Node | null = walker.nextNode()
  while (n) {
    if (n.nodeType === Node.TEXT_NODE) {
      processTextNode(n as Text, lang)
    } else if (n.nodeType === Node.ELEMENT_NODE) {
      processElementAttrs(n as Element, lang)
    }
    n = walker.nextNode()
  }
}

function flushDirty() {
  rafId = 0
  if (currentLang === 'ru') {
    dirtyRoots.clear()
    return
  }
  const roots = Array.from(dirtyRoots)
  dirtyRoots.clear()
  for (const r of roots) {
    if (r.isConnected) walkAndTranslate(r, currentLang)
  }
}

function ensureObserver() {
  if (observer || typeof MutationObserver === 'undefined' || !document.body) return
  observer = new MutationObserver(mutations => {
    if (currentLang === 'ru') return
    for (const m of mutations) {
      if (m.type === 'characterData') {
        const tn = m.target as Text
        if (writtenText.get(tn) === tn.nodeValue) continue
        dirtyRoots.add(tn)
      } else if (m.type === 'attributes') {
        const el = m.target as Element
        const attr = m.attributeName as typeof ATTRS[number] | null
        if (!attr || !ATTRS.includes(attr)) continue
        const w = writtenAttr.get(el)
        if (w && w[attr] === el.getAttribute(attr)) continue
        dirtyRoots.add(el)
      } else if (m.type === 'childList') {
        m.addedNodes.forEach(an => dirtyRoots.add(an))
      }
    }
    if (dirtyRoots.size && !rafId) {
      rafId = requestAnimationFrame(flushDirty)
    }
  })
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...ATTRS],
  })
}

export function setDomTranslateLang(lang: Lang) {
  currentLang = lang
  if (typeof document === 'undefined' || !document.body) return
  ensureObserver()
  // Run after React commits its own t(...) updates for the language switch
  requestAnimationFrame(() => {
    if (!document.body) return
    walkAndTranslate(document.body, currentLang)
    // Second pass catches lazy-rendered portals/effects
    setTimeout(() => {
      if (document.body) walkAndTranslate(document.body, currentLang)
    }, 120)
  })
}
