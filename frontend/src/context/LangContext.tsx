export type Lang='ru'|'en'|'kg'
const VALID_LANGS: Lang[] = ['ru','en','kg']

function initialLang(): Lang {
  try {
    const v = localStorage.getItem('lang')
    return VALID_LANGS.includes(v as Lang) ? (v as Lang) : 'ru'
  } catch { return 'ru' }
}

/** Monaco знает не все локали: кыргызской нет — берём русскую. */
export function monacoLocale(lang: Lang): 'ru'|'en' {
  return lang === 'en' ? 'en' : 'ru'
}

